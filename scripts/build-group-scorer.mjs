// Bundle the same pure exports used by solo/group recommendations for Deno.
// No browser clients, API keys or data-fetching exports are retained.
import { build } from "esbuild";
const result = await build({
  stdin: {
    contents:
      "export { buildTasteProfile, scoreCandidates, buildCandidateQueries } from './src/lib/recommendations'; export { aggregateGroup, groupVeto } from './src/lib/group-recs';",
    resolveDir: process.cwd(),
  },
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  treeShaking: true,
  write: false,
  plugins: [
    {
      name: "pure-ranking",
      setup(b) {
        b.onResolve({ filter: /.*/ }, async (args) => {
          if (args.pluginData?.resolved) return;
          const r = await b.resolve(args.path, {
            resolveDir: args.resolveDir,
            kind: args.kind,
            pluginData: { resolved: true },
          });
          return { ...r, sideEffects: false };
        });
      },
    },
  ],
});
const output = result.outputFiles[0].text;
if (/createClient\(|localStorage|import\.meta|ANTHROPIC_API_KEY/.test(output))
  throw Error("Browser or secret dependency leaked into scoring bundle");
const { writeFile } = await import("node:fs/promises");
await writeFile(
  "supabase/functions/group-swipe/scorer.js",
  "// Generated by scripts/build-group-scorer.mjs. Do not edit.\n" + output,
);
